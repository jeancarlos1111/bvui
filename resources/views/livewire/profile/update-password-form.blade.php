            <button type="submit" class="inline-flex items-center justify-center px-6 py-2.5 text-sm font-medium tracking-wide text-white transition-all duration-200 bg-gradient-to-r from-gray-800 to-gray-900 rounded-xl hover:shadow-lg hover:shadow-gray-900/30 focus:ring-2 focus:ring-offset-2 focus:ring-gray-900">
